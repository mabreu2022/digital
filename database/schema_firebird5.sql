/*----------------------------------------------------------------------------
  1. TABELA: TELAS (Players cadastrados e seus estados de telemetria)
----------------------------------------------------------------------------*/
CREATE TABLE TELAS (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    UUID VARCHAR(36) NOT NULL,
    NOME VARCHAR(100) NOT NULL,
    IP_LOCAL VARCHAR(45),
    IP_PUBLICO VARCHAR(45),
    MAC_ADDRESS VARCHAR(30),
    SISTEMA_OPERACIONAL VARCHAR(50),
    VERSAO_PLAYER VARCHAR(20),
    STATUS VARCHAR(20) DEFAULT 'OFFLINE' NOT NULL, -- 'ONLINE', 'OFFLINE', 'SYNCING', 'ERROR'
    ULTIMO_HEARTBEAT TIMESTAMP,
    LARGURA_PX INTEGER DEFAULT 1920,
    ALTURA_PX INTEGER DEFAULT 1080,
    ORIENTACAO VARCHAR(10) DEFAULT 'LANDSCAPE', -- 'LANDSCAPE', 'PORTRAIT'
    VOLUME_AUDIO INTEGER DEFAULT 100,
    STORAGE_TOTAL_MB BIGINT,
    STORAGE_LIVRE_MB BIGINT,
    CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ATUALIZADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT UNQ_TELAS_UUID UNIQUE (UUID)
);

CREATE INDEX IDX_TELAS_STATUS ON TELAS (STATUS);
CREATE INDEX IDX_TELAS_HEARTBEAT ON TELAS (ULTIMO_HEARTBEAT);

/*----------------------------------------------------------------------------
  2. TABELA: MIDIAS (Catálogo centralizado de conteúdos)
----------------------------------------------------------------------------*/
CREATE TABLE MIDIAS (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOME_EXIBICAO VARCHAR(150) NOT NULL,
    NOME_ARQUIVO VARCHAR(255) NOT NULL,
    HASH_MD5 VARCHAR(32) NOT NULL,
    TAMANHO_BYTES BIGINT NOT NULL,
    TIPO_MIDIA VARCHAR(20) NOT NULL, -- 'VIDEO', 'IMAGE', 'HTML', 'STREAM'
    MIME_TYPE VARCHAR(100),
    DURACAO_PADRAO_SEG INTEGER DEFAULT 10 NOT NULL,
    LARGURA_PX INTEGER,
    ALTURA_PX INTEGER,
    URL_DOWNLOAD VARCHAR(1000) NOT NULL,
    STATUS VARCHAR(20) DEFAULT 'READY' NOT NULL, -- 'PROCESSING', 'READY', 'ARCHIVED'
    CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ATUALIZADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT UNQ_MIDIAS_MD5 UNIQUE (HASH_MD5)
);

CREATE INDEX IDX_MIDIAS_TIPO ON MIDIAS (TIPO_MIDIA);

/*----------------------------------------------------------------------------
  3. TABELA: PLAYLISTS (Listas de reprodução)
----------------------------------------------------------------------------*/
CREATE TABLE PLAYLISTS (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOME VARCHAR(100) NOT NULL,
    DESCRICAO VARCHAR(255),
    IS_PADRAO SMALLINT DEFAULT 0 NOT NULL, -- 1 = Playlist de Fallback padrão
    ATIVA SMALLINT DEFAULT 1 NOT NULL,     -- 1 = Ativa, 0 = Inativa
    CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ATUALIZADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE INDEX IDX_PLAYLISTS_ATIVA ON PLAYLISTS (ATIVA);
CREATE INDEX IDX_PLAYLISTS_PADRAO ON PLAYLISTS (IS_PADRAO);

/*----------------------------------------------------------------------------
  4. TABELA: PLAYLIST_ITENS (Itens vinculados à playlist com ordem e duração)
----------------------------------------------------------------------------*/
CREATE TABLE PLAYLIST_ITENS (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PLAYLIST_ID BIGINT NOT NULL,
    MIDIA_ID BIGINT NOT NULL,
    ORDEM INTEGER DEFAULT 1 NOT NULL,
    DURACAO_EXIBICAO_SEG INTEGER NOT NULL, -- Tempo de exibição customizado
    TRANSICAO VARCHAR(30) DEFAULT 'CUT',   -- 'CUT', 'FADE', 'SLIDE_LEFT', etc.
    CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_PL_ITENS_PLAYLIST FOREIGN KEY (PLAYLIST_ID) REFERENCES PLAYLISTS (ID) ON DELETE CASCADE,
    CONSTRAINT FK_PL_ITENS_MIDIA FOREIGN KEY (MIDIA_ID) REFERENCES MIDIAS (ID)
);

CREATE INDEX IDX_PL_ITENS_ORDEM ON PLAYLIST_ITENS (PLAYLIST_ID, ORDEM);

/*----------------------------------------------------------------------------
  5. TABELA: AGENDAMENTOS (Grade horária, janelas, dias da semana e prioridade)
----------------------------------------------------------------------------*/
CREATE TABLE AGENDAMENTOS (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TELA_ID BIGINT,                          -- NULL indica agendamento global (todas as telas)
    PLAYLIST_ID BIGINT NOT NULL,
    NOME_EVENTO VARCHAR(100) NOT NULL,
    DATA_INICIO DATE NOT NULL,
    DATA_FIM DATE NOT NULL,
    HORA_INICIO TIME NOT NULL,
    HORA_FIM TIME NOT NULL,
    DIAS_SEMANA VARCHAR(7) DEFAULT '1111111' NOT NULL, -- String binária 'DOM,SEG,TER,QUA,QUI,SEX,SAB' (ex: '0111110' = Seg a Sex)
    PRIORIDADE INTEGER DEFAULT 1 NOT NULL,  -- Maior valor = maior prioridade de sobreposição
    ATIVO SMALLINT DEFAULT 1 NOT NULL,
    CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ATUALIZADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_AGEND_TELA FOREIGN KEY (TELA_ID) REFERENCES TELAS (ID) ON DELETE CASCADE,
    CONSTRAINT FK_AGEND_PLAYLIST FOREIGN KEY (PLAYLIST_ID) REFERENCES PLAYLISTS (ID) ON DELETE CASCADE
);

CREATE INDEX IDX_AGEND_TELA_DATA ON AGENDAMENTOS (TELA_ID, ATIVO, DATA_INICIO, DATA_FIM);
CREATE DESCENDING INDEX IDX_AGEND_PRIORIDADE ON AGENDAMENTOS (PRIORIDADE);

/*----------------------------------------------------------------------------
  6. TABELA: LOGS_EXIBICAO (Proof-of-Play para auditoria e relatórios de clientes)
----------------------------------------------------------------------------*/
CREATE TABLE LOGS_EXIBICAO (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TELA_ID BIGINT NOT NULL,
    MIDIA_ID BIGINT NOT NULL,
    PLAYLIST_ID BIGINT,
    DATA_HORA_INICIO TIMESTAMP NOT NULL,
    DATA_HORA_FIM TIMESTAMP NOT NULL,
    SEGUNDOS_EXIBIDOS INTEGER NOT NULL,
    STATUS_EXIBICAO VARCHAR(30) DEFAULT 'COMPLETED' NOT NULL, -- 'COMPLETED', 'INTERRUPTED', 'ERROR'
    MENSAGEM_ERRO VARCHAR(255),
    CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_LOGS_TELA FOREIGN KEY (TELA_ID) REFERENCES TELAS (ID) ON DELETE CASCADE,
    CONSTRAINT FK_LOGS_MIDIA FOREIGN KEY (MIDIA_ID) REFERENCES MIDIAS (ID) ON DELETE CASCADE
);

CREATE INDEX IDX_LOGS_TELA_DATA ON LOGS_EXIBICAO (TELA_ID, DATA_HORA_INICIO);
CREATE INDEX IDX_LOGS_MIDIA_DATA ON LOGS_EXIBICAO (MIDIA_ID, DATA_HORA_INICIO);

/*----------------------------------------------------------------------------
  7. TRIGGERS DE ATUALIZAÇÃO AUTOMÁTICA DE TIMESTAMP (ATUALIZADO_EM)
----------------------------------------------------------------------------*/
SET TERM ^ ;

CREATE OR ALTER TRIGGER TRG_TELAS_BIU FOR TELAS
ACTIVE BEFORE INSERT OR UPDATE POSITION 0
AS
BEGIN
    NEW.ATUALIZADO_EM = CURRENT_TIMESTAMP;
END^

CREATE OR ALTER TRIGGER TRG_MIDIAS_BIU FOR MIDIAS
ACTIVE BEFORE INSERT OR UPDATE POSITION 0
AS
BEGIN
    NEW.ATUALIZADO_EM = CURRENT_TIMESTAMP;
END^

CREATE OR ALTER TRIGGER TRG_PLAYLISTS_BIU FOR PLAYLISTS
ACTIVE BEFORE INSERT OR UPDATE POSITION 0
AS
BEGIN
    NEW.ATUALIZADO_EM = CURRENT_TIMESTAMP;
END^

CREATE OR ALTER TRIGGER TRG_AGENDAMENTOS_BIU FOR AGENDAMENTOS
ACTIVE BEFORE INSERT OR UPDATE POSITION 0
AS
BEGIN
    NEW.ATUALIZADO_EM = CURRENT_TIMESTAMP;
END^

SET TERM ; ^

